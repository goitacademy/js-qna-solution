/**
 * Рішення для ментора: «Форматування цін»
 *
 * map() викликає колбек для кожного елемента та повертає новий масив тієї ж
 * довжини. Вираз після => повертається неявно. Початкові числа не змінюються.
 */
const prices = [120, 450, 80, 999];
const formattedPrices = prices.map(price => `${price} грн`);
console.log(formattedPrices);
